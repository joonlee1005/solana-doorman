const DOW_EN: Record<string, string> = {
  일: "SUN",
  월: "MON",
  화: "TUE",
  수: "WED",
  목: "THU",
  금: "FRI",
  토: "SAT",
};

/** Swaps `(월)`-style Korean weekday parens for English abbreviations when lang is "en". */
export function localizeDate(date: string, lang: Lang): string {
  if (lang !== "en") return date;
  return date.replace(/\(([일월화수목금토])\)/g, (_m, d: string) => `(${DOW_EN[d]})`);
}
